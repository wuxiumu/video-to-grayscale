import { chromium } from '@playwright/test';
import { run } from '../src/core/process.js';
import { serve } from '../src/server/http.js';
import { mkdir, mkdtemp, rm, access } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
const temp = await mkdtemp(path.join(os.tmpdir(), 'gray-browser-'));
let sample = path.resolve('test/2026-09-15_153332_222.mp4');
try { await access(sample); } catch {
  await mkdir(path.join(temp, 'input'));
  sample = path.join(temp, 'input', '2026-09-15_153332_222.mp4');
  await run('ffmpeg', ['-v', 'error', '-f', 'lavfi', '-i', 'testsrc2=size=320x240:rate=24', '-t', '1', '-c:v', 'libx264', sample]);
}
await mkdir('output', { recursive: true });
const app = await serve({ inputDir: path.dirname(sample), outputDir: path.join(temp, 'output'), dataDir: path.join(temp, 'data'), port: 0, open: false });
const executablePath = process.env.CHROME_PATH || (process.platform === 'darwin' ? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' : undefined);
let browser;
try {
  browser = await chromium.launch({ executablePath, headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1150 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error' && !message.text().includes('favicon')) errors.push(message.text()); });
  await page.goto(app.url);
  await page.locator('#mode').selectOption('grayscale');
  await page.getByText('本地转换引擎已就绪').waitFor();
  await page.getByRole('checkbox', { name: '选择 2026-09-15_153332_222.mp4', exact: true }).check();
  await page.getByRole('button', { name: '开始转换' }).click();
  await page.getByRole('button', { name: '播放', exact: true }).waitFor({ timeout: 30000 });
  await page.screenshot({ path: 'output/ui-desktop.png', fullPage: true });
  await page.getByRole('button', { name: '播放', exact: true }).click();
  await page.locator('#player').evaluate(video => video.play());
  await page.waitForFunction(() => document.getElementById('player').currentTime > 0.1);
  await page.getByRole('button', { name: '关闭 ✕' }).first().click();
  await page.reload(); await page.locator('#mode').selectOption('grayscale'); await page.getByRole('button', { name: '播放', exact: true }).waitFor();
  await page.locator('#file-input').setInputFiles(sample);
  await page.locator('#imported-section .file-row').waitFor();
  await page.waitForFunction(() => !document.getElementById('convert').disabled);
  await page.getByRole('button', { name: '开始转换' }).click();
  await page.waitForFunction(() => document.querySelectorAll('.job.completed').length === 2, null, { timeout: 30000 });
  await page.getByRole('button', { name: 'Ⅱ 暂停队列' }).click();
  await page.getByRole('button', { name: '▶ 继续队列' }).waitFor();
  await page.getByRole('checkbox', { name: '选择 2026-09-15_153332_222.mp4', exact: true }).first().check();
  await page.getByRole('button', { name: '开始转换' }).click();
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await page.getByRole('button', { name: '重试', exact: true }).waitFor();
  await page.getByRole('button', { name: '重试', exact: true }).click();
  await page.getByRole('button', { name: '▶ 继续队列' }).click();
  await page.waitForFunction(() => document.querySelectorAll('.job.completed').length === 3, null, { timeout: 30000 });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'output/ui-mobile.png', fullPage: true });
  await page.reload(); await page.locator('#mode').selectOption('grayscale');
  await page.locator('#imported-section .file-row').waitFor();
  await page.getByRole('button', { name: '清理已结束', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('.job').length === 0);
  assert.equal((await page.locator('#notice').innerText()).includes('原片与导出结果均保留'), true);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'mobile overflow');
  assert.deepEqual(errors, []);
  console.log('Browser PASS: sample conversion, playback, refresh, upload, queue pause/cancel/retry, mobile layout; no JS errors');
} finally { await browser?.close(); await app.close(); await rm(temp, { recursive: true, force: true }); }
